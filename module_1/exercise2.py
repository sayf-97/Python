# Exercise 2 - Explore List Operations

# Create a list containing five items
tasks = [
    "Learn Python",
    "Practice lists",
    "Read a book",
    "Go for a walk",
    "Build a project"
]

print("First item:")
print(tasks[0])

print("\nLast item:")
print(tasks[4])

print("\nNumber of items:")
print(len(tasks))

# Add another item
tasks.append("Practice coding")

print("\nList after adding an item:")
print(tasks)

print("\nNew number of items:")
print(len(tasks))


